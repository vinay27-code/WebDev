// Arithmetic operators are used to calculate mathematical operations

let a=10;
let b=5;

console.log(a+b);       //add
console.log(a-b);       //subtract
console.log(a*b);       //multiply
console.log(a/b);       //divide
console.log(a%b);       //modulus
console.log(a**b);      //power(a power b)

// output:
// 15
// 5
// 50
// 2
// 0
// 100000