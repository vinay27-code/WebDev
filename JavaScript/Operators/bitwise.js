// Bitwise AND

let a=2;        //a in binary form is: 010
let b=3;        //b in binary form is: 011

console.log(a&b);       //output: 2

// Bitwise OR

console.log(a|b);

// Bitwise XOR

console.log(a^b);      //output: 1

// Bitwise leftShift

console.log(a<<2);      //010.0000 => 01000.00 => 8

// Bitwise RightShift

console.log(a>>2);      //010.0000 => 0.100000 => 0