//In javascript, the number data type is used to represent both integer and floating-point numbers. 
// It can be used for mathematical operations, comparisons, and more. 
// Here are some examples of how to use the number data type in JavaScript:

let number1=10; // integer
let number2=3.14; // floating-point number

// Performing mathematical operations
let sum=number1+number2;
let difference=number1-number2;
let product=number1*number2;
let quotient=number1/number2;

console.log("Sum:",sum);
console.log("Difference:",difference);
console.log("Product:",product);
console.log("Quotient:",quotient);

// Comparisons
console.log("Is number1 greater than number2?", number1>number2);
console.log("Is number1 equal to number2?", number1==number2);