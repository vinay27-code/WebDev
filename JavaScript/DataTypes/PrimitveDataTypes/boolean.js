// boolean data type is used to represent logical values, which can be either true or false. 
// In JavaScript, the boolean data type is a primitive data type that can be used in various programming scenarios, such as conditional statements and loops.

// Here are some examples of how to use the boolean data type in JavaScript:

let isJavaScriptFun = true; // boolean value true
let isCodingHard = false; // boolean value false

console.log("Is JavaScript fun?", isJavaScriptFun);
console.log("Is coding hard?", isCodingHard);

// Boolean values can also be the result of comparisons or logical operations.
let number1 = 10;
let number2 = 20;

let isNumber1GreaterThanNumber2 = number1 > number2; // false
let isNumber1LessThanNumber2 = number1 < number2; // true

console.log("Is number1 greater than number2?", isNumber1GreaterThanNumber2);
console.log("Is number1 less than number2?", isNumber1LessThanNumber2);

console.log(typeof(isJavaScriptFun)); // Output: boolean