// Undefined is a primitive data type in JavaScript that represents the absence of a value or an uninitialized variable. 
// It is a special value that indicates that a variable has not been assigned a value yet.

let a;

console.log(a); // Output: undefined

// You can also explicitly assign the value undefined to a variable.
let b = undefined;

console.log(b); // Output: undefined

// It's important to note that undefined is different from null. 
// Undefined means a variable has been declared but has not yet been assigned a value, while null is an assignment value that represents no value or no object.

let c = null;

console.log(c); // Output: null

console.log(typeof(a)); // Output: undefined