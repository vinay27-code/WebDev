// String using double quotes
let s1="Vinay";

// String using single quotes
let s2='Vinay';

// String using backquotes. This allows us to create multi line strings
let s3=`Vinay 
is a good boy`;

console.log(s1);
console.log(s2);
console.log(s3);

// output:
// Vinay
// Vinay
// Vinay 
// is a good boy