// We can insert an element into the arary at the end of it, using push() method.

let arr=[1,2,3,4,5];

arr.push(6);

console.log(arr);       //[ 1, 2, 3, 4, 5, 6 ]

arr.push(7);

console.log(arr);       //[ 1, 2, 3, 4, 5, 6, 7 ]

// We can remove an element from the array from its end, using pop() method

arr.pop();
console.log(arr);       //[ 1, 2, 3, 4, 5, 6 ]

arr.pop();
console.log(arr);       //[ 1, 2, 3, 4, 5 ]